def encode(source, destination, max_edge, quality):
    original_hash = hashlib.sha256(source.read_bytes()).digest()
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original)
        original_pixels = image.width * image.height
        if max_edge:
            image.thumbnail((max_edge, max_edge), Image.Resampling.LANCZOS)
        destination.parent.mkdir(parents=True, exist_ok=True)
        image.save(destination, "WEBP", quality=quality, method=6)
        output_pixels = image.width * image.height
    assert hashlib.sha256(source.read_bytes()).digest() == original_hash, source
    return source.stat().st_size, destination.stat().st_size, original_pixels, output_pixels


def summarize(label, rows):
    before, after, pixels_before, pixels_after = (sum(row[i] for row in rows) for i in range(4))
    print(f"{label}: {len(rows)} images; {before:,} -> {after:,} bytes "
          f"({100 * (1 - after / before):.1f}% smaller); "
          f"RGBA {pixels_before * 4 / 1048576:.2f} -> {pixels_after * 4 / 1048576:.2f} MiB")


def write_map_module(map_files):
    map_json = json.dumps(sorted(map_files), ensure_ascii=False, indent=2)
    (ROOT / "src/map-assets.js").write_text(
        "// Generated by scripts/optimize-assets.py. Original artwork stays available for previews.\n"
        f"export const MAP_ASSET_FILES = Object.freeze({map_json});\n"
        "const mapFiles = new Set(MAP_ASSET_FILES);\n\n"
        "export function mapAsset(file, baseUrl = import.meta.env?.BASE_URL ?? '/') {\n"
        "  const normalized = file.replace(/\\.png$/, '.webp');\n"
        "  const base = baseUrl.endsWith('/') ? baseUrl : `${baseUrl}/`;\n"
        "  return `${base}assets/${mapFiles.has(normalized) ? 'map/' : ''}${normalized}`;\n"
        "}\n", encoding="utf-8")


def main():
    map_rows = []
    map_files = []
    for filename in MAP_SOURCES:
        normalized = str(Path(filename).with_suffix(".webp"))
        terrain = filename.startswith("terrain/")
        max_edge = None if terrain else 384 if filename.startswith("game-portraits/") else 640
        map_rows.append(encode(ASSETS / filename, ASSETS / "map" / normalized, max_edge, 85 if terrain else 88))
        map_files.append(normalized)
    write_map_module(map_files)

    catalogue = json.loads(subprocess.check_output([
        "node", "--input-type=module", "-e",
        "import { PHOTOS } from './src/photos.js'; console.log(JSON.stringify(PHOTOS));",
    ], cwd=ROOT, text=True))
    thumbnails = {}
    photo_rows = []
    for photo in catalogue:
        thumbnail = f"memories/thumbs/{photo['id']}.webp"
        photo_rows.append(encode(ASSETS / photo["src"], ASSETS / thumbnail, 320, 84))
        thumbnails[photo["src"]] = thumbnail
    thumb_json = json.dumps(thumbnails, ensure_ascii=False, indent=2)
    (ROOT / "src/photo-thumbnails.js").write_text(
        "// Generated by scripts/optimize-assets.py; photo assignment sync leaves this file intact.\n"
        f"export const PHOTO_THUMBNAILS = Object.freeze({thumb_json});\n",
        encoding="utf-8")
    summarize("Map", map_rows)
    summarize("Photo thumbnails", photo_rows)


if __name__ == "__main__":
    main()
