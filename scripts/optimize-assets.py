#!/usr/bin/env python3
"""Generate map variants and album thumbnails without changing source images.

Run from any directory: python3 scripts/optimize-assets.py
Requires Node.js and Pillow (tested with Pillow 12.3.0). Commit the generated
assets/modules, so the deployed site and its build need neither dependency.
After adding photos to src/photos.js, run this command again. Photo assignment
sync only updates photo-assignments.json and does not overwrite these mappings.
"""

